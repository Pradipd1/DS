"""
DEMO: Self-Healing Deep Learning System for Continual Learning
in Dynamic Environments

What this demo shows (in order):
1. A base model trained on initial data.
2. Live data streamed in batches -- after batch 8, we simulate
   the environment changing (concept drift).
3. The system MONITORS its own accuracy every batch.
4. When accuracy falls below a threshold, drift is DETECTED.
5. A DIAGNOSIS step (representing the LLM's role) explains why
   accuracy dropped and recommends a repair action.
6. SELF-REPAIR: the model retrains using a memory buffer (old +
   new data) to fix itself WITHOUT forgetting old patterns.
7. A plot shows accuracy recovering right after each repair.
"""

import numpy as np
from sklearn.linear_model import SGDClassifier
from sklearn.metrics import accuracy_score
import matplotlib.pyplot as plt

np.random.seed(42)

DRIFT_THRESHOLD = 0.75


def generate_batch(shift=0.0, n=200):
    """Creates one batch of synthetic streaming data.
    'shift' simulates how much the environment has changed."""
    X = np.random.randn(n, 4)
    true_weights = np.array([1.5, -2.0, 1.0, 0.5]) + shift
    y = (X @ true_weights > 0).astype(int)
    return X, y


def llm_diagnose(accuracy, drift_score):
    """
    Simulated diagnostic module.

    In the full system this text would be generated by the LLM
    (LLaMA 3.1) after reading the real performance logs and drift
    scores. Here the same logic is written directly in Python so
    the demo runs instantly and reliably, without needing an API
    key or GPU during the live review.
    """
    if accuracy < DRIFT_THRESHOLD:
        diagnosis = (
            f"Accuracy fell to {accuracy:.2f} while drift score is "
            f"{drift_score:.2f}. Likely cause: input feature "
            f"distribution has shifted (concept drift). "
            f"Recommended action: retrain on the most recent batch "
            f"combined with replayed past samples, to fix the drop "
            f"without forgetting older patterns."
        )
        return diagnosis, True
    return "No significant drift detected. Model is healthy.", False


def run_demo():
    # ---- Step 1: Train the base model ----
    X_train, y_train = generate_batch(shift=0.0, n=500)
    model = SGDClassifier(loss="log_loss")
    model.partial_fit(X_train, y_train, classes=[0, 1])

    memory_X, memory_y = X_train.copy(), y_train.copy()

    accuracy_log = []
    drift_batches = []
    healing_points = []

    print("=== SELF-HEALING DEEP LEARNING SYSTEM : LIVE DEMO ===\n")

    # ---- Step 2 to 7: Stream data batch by batch ----
    for t in range(20):
        # environment starts drifting after batch 8
        shift = 0.0 if t < 8 else (t - 8) * 0.25
        X_batch, y_batch = generate_batch(shift=shift, n=200)

        preds = model.predict(X_batch)
        acc = accuracy_score(y_batch, preds)
        accuracy_log.append(acc)

        drift_score = abs(shift)
        diagnosis, needs_repair = llm_diagnose(acc, drift_score)

        print(f"Batch {t + 1:2d} | Accuracy: {acc:.2f} | Drift score: {drift_score:.2f}")

        if needs_repair:
            drift_batches.append(t)
            print(f"   >> DIAGNOSIS: {diagnosis}")

            # ---- SELF-REPAIR: retrain on memory buffer + new batch ----
            memory_X = np.vstack([memory_X[-300:], X_batch])
            memory_y = np.concatenate([memory_y[-300:], y_batch])
            model.partial_fit(memory_X, memory_y)

            preds_after = model.predict(X_batch)
            acc_after = accuracy_score(y_batch, preds_after)
            healing_points.append((t, acc_after))
            print(f"   >> SELF-REPAIR APPLIED. Accuracy recovered to {acc_after:.2f}\n")
        else:
            print()

    # ---- Plot the full run ----
    plt.figure(figsize=(9, 5))
    plt.plot(range(1, 21), accuracy_log, marker='o', label="Accuracy per batch")
    for i, dp in enumerate(drift_batches):
        plt.axvline(dp + 1, color='red', linestyle='--', alpha=0.4,
                     label="Drift detected" if i == 0 else "")
    for i, (hp, acc) in enumerate(healing_points):
        plt.scatter(hp + 1, acc, color='green', s=100, zorder=5,
                     label="Accuracy after self-repair" if i == 0 else "")
    plt.axhline(DRIFT_THRESHOLD, color='orange', linestyle=':', label="Drift threshold")
    plt.title("Self-Healing Deep Learning System -- Accuracy Over Time")
    plt.xlabel("Batch Number (simulated time)")
    plt.ylabel("Accuracy")
    plt.ylim(0.3, 1.0)
    plt.legend()
    plt.tight_layout()
    plt.savefig("demo_accuracy_plot.png", dpi=150)
    print("Plot saved as demo_accuracy_plot.png")


if __name__ == "__main__":
    run_demo()
